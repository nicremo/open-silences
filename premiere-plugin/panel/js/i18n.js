export const MESSAGES = Object.freeze({ en: Object.freeze(en), es: Object.freeze(es), de: Object.freeze(de) });

/** Maps a locale such as "de_DE" or "es-MX" to a supported language, English otherwise. */
export function resolveLanguage(code) {
  const prefix = String(code || '').toLowerCase().split(/[-_]/)[0];
  return LANGUAGES.some(language => language.code === prefix) ? prefix : 'en';
}

/** t(key, vars) for one language, with t.plural(key, count, vars) and English fallback. */
export function createTranslator(language) {
  const code = Object.prototype.hasOwnProperty.call(MESSAGES, language) ? language : 'en';
  const table = MESSAGES[code];
  const t = (key, vars = {}) => {
    const template = table[key] ?? MESSAGES.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
  };
  t.plural = (key, count, vars = {}) => t(`${key}.${count === 1 ? 'one' : 'other'}`, { count, ...vars });
  t.language = code;
  return t;
}

/** Durations and shares with one decimal: "11.5 s" and "19.1%" in English, "11,5 s" and "19,1 %" otherwise. */
export function createFormat(language) {
  const comma = resolveLanguage(language) !== 'en';
  const decimal = value => {
    const text = Number(value).toFixed(1);
    return comma ? text.replace('.', ',') : text;
  };
  return {
    decimal,
    seconds: value => `${decimal(value)} s`,
    clock: value => {
      const total = Math.max(0, Math.round(Number(value) || 0));
      return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, '0')} min`;
    },
    percent: (part, whole) => {
      const share = decimal(whole > 0 ? (part / whole) * 100 : 0);
      return comma ? `${share} %` : `${share}%`;
    }
  };
}
